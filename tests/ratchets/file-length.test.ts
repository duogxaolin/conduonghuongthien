import assert from 'node:assert/strict'
import test from 'node:test'
import {
  baselinePath, baselineProblems, compare, describeRegressions, entryValue, isExempt, measureFiles, ratchet, readBaseline,
  updateBaseline, type Baseline, type FileRatchet,
} from './_ratchet'

/**
 * File-length ratchet (wave3-long-term D-R, task 1.2).
 *
 * Lines per source file, counted like `wc -l` (the number of newline characters, so a
 * last line without a newline does not count). A new file may have at most 400 lines;
 * a file over 400 lines today may not grow. Splitting follows D-SPLIT and the guard
 * constraints in docs/decisions/refactor-large-files.md.
 *
 * Two kinds of named entry, each with its `reason` in the baseline:
 *   - CAPPED with a reason — allowed above 400 for good, but may only shrink; growing
 *     needs `--raise <file>` in that PR. The two unsplittable files, whose guard tests pin
 *     the parent file's template (and, for the dashboard, run its script through
 *     `Function()`): `app/pages/admin/content/articles/index.vue`,
 *     `app/components/admin/AnalyticsLiveDashboard.client.vue`.
 *   - EXEMPT and uncapped (`"exempt": true`) — append-only data by nature, so growth is
 *     not a regression: `server/db/schema.ts` (single source of truth, guarded by
 *     `db:drift`), `server/db/migrations-additive.ts` (append-only), and the content/seed
 *     files `app/composables/i18n-default-dictionary.ts`,
 *     `server/data/default-translations-seed.ts`, `server/data/chatbot-small-talk-seed.ts`.
 *     Still listed: a removed or renamed one fails as stale, and one that loses its reason
 *     fails. Only a hand edit makes an entry exempt; `--update` never does.
 * Every other file over 400 lines is capped debt.
 *
 * Baseline: tests/ratchets/file-length.baseline.json. Regenerate (lowers only):
 *   node --experimental-strip-types --import ./scripts/ts-resolver.mjs tests/ratchets/file-length.test.ts --update
 */

const MEASURED_EXTENSIONS = /\.(?:ts|vue|js|mjs|cjs|sh)$/

/** Allowed above 400 for good, still capped: may only shrink. */
const CAPPED_WITH_REASON = [
  'app/pages/admin/content/articles/index.vue',
  'app/components/admin/AnalyticsLiveDashboard.client.vue',
]

/** Append-only data: uncapped, but listed with a reason. */
const EXEMPT_UNCAPPED = [
  'server/db/schema.ts',
  'server/db/migrations-additive.ts',
  'app/composables/i18n-default-dictionary.ts',
  'server/data/default-translations-seed.ts',
  'server/data/chatbot-small-talk-seed.ts',
]

/**
 * Tracked files with a measured extension that are NOT measured, and why. Lockfiles
 * (`package-lock.json`) and other data never match the extensions above.
 */
export const NOT_MEASURED: ReadonlyArray<{ pattern: RegExp, reason: string }> = [
  { pattern: /^tests\//, reason: 'test code: table-driven suites and fixtures, not product code (design D-R)' },
  { pattern: /^public\//, reason: 'served static assets, including the vendored TinyMCE build under public/assets/tinymce' },
  { pattern: /^migrations\//, reason: 'mysqldump snapshots, not hand-written code' },
  { pattern: /^docs\//, reason: 'documentation' },
  { pattern: /^openspec\//, reason: 'change proposals' },
  { pattern: /\.d\.ts$/, reason: 'type declarations: generated by `nuxt prepare` into .nuxt/ (untracked) or describing an external API; none is tracked today' },
  { pattern: /\.min\.(?:js|mjs|cjs)$/, reason: 'minified vendor bundles' },
]

export const FILE_LENGTH: FileRatchet = {
  name: 'file-length',
  unit: 'lines',
  defaultForNewFiles: 400,
  inScope: file => MEASURED_EXTENSIONS.test(file) && !NOT_MEASURED.some(({ pattern }) => pattern.test(file)),
  measure: (text) => {
    let lines = 0
    for (let i = text.indexOf('\n'); i !== -1; i = text.indexOf('\n', i + 1)) lines += 1
    return lines
  },
  hint: 'Split the file: extract presentational subcomponents and pure helpers, keeping state, error/retry and role="alert" in the parent (design D-SPLIT, docs/decisions/refactor-large-files.md).',
}

ratchet(FILE_LENGTH, () => {
  test('file-length: counts lines the way `wc -l` does', () => {
    assert.equal(FILE_LENGTH.measure('', 'a.ts'), 0)
    assert.equal(FILE_LENGTH.measure('one line, no newline', 'a.ts'), 0)
    assert.equal(FILE_LENGTH.measure('a\nb\n', 'a.ts'), 2)
    assert.equal(FILE_LENGTH.measure('a\nb', 'a.ts'), 1)
    assert.equal(FILE_LENGTH.measure('a\r\nb\r\n\n', 'a.ts'), 3)
  })

  test('file-length: measures source and shell files, and names every exclusion with a reason', () => {
    for (const file of ['app/pages/index.vue', 'server/db/schema.ts', 'scripts/fetch-fonts.mjs', 'ecosystem.config.cjs',
      'tailwind.config.js', 'production/manage.sh', 'docker/mysql-autotune.sh', 'nuxt.config.ts']) {
      assert.ok(FILE_LENGTH.inScope(file), file)
    }
    for (const file of ['tests/ops-scripts.test.ts', 'public/assets/tinymce/tinymce.min.js', 'public/sw.js', 'migrations/001.sql',
      'docs/x.ts', 'openspec/x.ts', 'app/types/env.d.ts', 'package-lock.json', 'app/assets/css/main.css', 'Dockerfile', 'README.md']) {
      assert.ok(!FILE_LENGTH.inScope(file), file)
    }
    for (const { reason } of NOT_MEASURED) assert.ok(reason.trim().length > 10)
  })

  test('file-length: each named entry keeps its kind and its reason; no other entry is exempt', () => {
    const baseline = readBaseline(baselinePath(FILE_LENGTH.name))
    for (const file of CAPPED_WITH_REASON) {
      const entry = baseline[file]
      if (entry === undefined) continue // at or under 400 now: nothing left to allow
      assert.ok(typeof entry === 'object' && !isExempt(entry) && typeof entry.value === 'number' && entry.reason.trim() !== '',
        `${file} must stay CAPPED with a reason ({ "value", "reason" }) — it is unsplittable, not append-only`)
    }
    for (const file of EXEMPT_UNCAPPED) {
      const entry = baseline[file]
      assert.ok(entry !== undefined && isExempt(entry) && typeof entry.reason === 'string' && entry.reason.trim() !== '',
        `${file} must be listed as { "exempt": true, "reason": "…" } (append-only data, design D-R)`)
    }
    const unexpected = Object.entries(baseline).filter(([file, entry]) => isExempt(entry) && !EXEMPT_UNCAPPED.includes(file)).map(([file]) => file)
    assert.deepEqual(unexpected, [], 'only the append-only files named in this test may be exempt; everything else over 400 lines stays capped')
  })

  // The two kinds, on the real baseline: every capped file exactly at its entry, every
  // exempt file at its real line count — so these tests check the rules, not the tree
  // (the ratchet test above checks the tree).
  const real = () => {
    const baseline = readBaseline(baselinePath(FILE_LENGTH.name))
    const measured = measureFiles(FILE_LENGTH)
    const current = new Map(Object.entries(baseline).map(([file, entry]) => [file, isExempt(entry) ? measured.get(file) ?? 0 : entryValue(entry)]))
    return { baseline, current }
  }

  test('file-length: an exempt file growing passes; a capped-with-reason file growing fails', () => {
    const { baseline, current } = real()
    const grown = new Map(current)
    for (const file of EXEMPT_UNCAPPED) grown.set(file, (current.get(file) ?? 0) + 500)
    const exemptOnly = compare(FILE_LENGTH, grown, baseline)
    assert.deepEqual(exemptOnly.worse, [], 'growth of an exempt file must not count as a regression')
    assert.deepEqual(exemptOnly.exempt.map(item => item.file).sort(), [...EXEMPT_UNCAPPED].sort())

    const dashboard = 'app/components/admin/AnalyticsLiveDashboard.client.vue'
    grown.set(dashboard, (current.get(dashboard) ?? 0) + 1)
    const capped = compare(FILE_LENGTH, grown, baseline)
    assert.deepEqual(capped.worse.map(item => item.file), [dashboard])
    assert.match(describeRegressions(FILE_LENGTH, capped), /AnalyticsLiveDashboard\.client\.vue: \d+ lines, baseline \d+ \(\+1\)\n {4}capped, with reason: Unsplittable/)
  })

  test('file-length: an exempt entry without its reason fails the baseline check', () => {
    const { baseline } = real()
    for (const reason of [undefined, '', '   ']) {
      const broken = { ...baseline, 'server/db/schema.ts': reason === undefined ? { exempt: true } : { exempt: true, reason } }
      assert.ok(baselineProblems(FILE_LENGTH, broken).some(problem => problem.startsWith('server/db/schema.ts: an object entry needs a non-empty "reason"')))
    }
    assert.deepEqual(baselineProblems(FILE_LENGTH, baseline), [])
    // Malformed exempt entries are rejected too.
    assert.ok(baselineProblems(FILE_LENGTH, { 'server/db/schema.ts': { exempt: 'yes', reason: 'x' } })[0]!.includes('"exempt" must be true'))
    assert.ok(baselineProblems(FILE_LENGTH, { 'server/db/schema.ts': { exempt: true, value: 1496, reason: 'x' } })[0]!.includes('takes no "value"'))
  })

  test('file-length: --update leaves exempt entries alone, and never makes an entry exempt', () => {
    const { baseline, current } = real()
    const changed = new Map(current)
    changed.set('server/db/schema.ts', 2000) // grew
    changed.set('server/db/migrations-additive.ts', 120) // shrank below the default
    changed.delete('server/data/chatbot-small-talk-seed.ts') // gone
    const dashboard = 'app/components/admin/AnalyticsLiveDashboard.client.vue'
    changed.set(dashboard, 2000) // capped with reason: grew
    const update = updateBaseline(FILE_LENGTH, changed, baseline, new Set([dashboard, 'server/db/schema.ts']))
    for (const file of EXEMPT_UNCAPPED) assert.deepEqual(update.baseline[file], baseline[file], `${file} was changed by --update`)
    assert.deepEqual(update.staleExempt, ['server/data/chatbot-small-talk-seed.ts'], 'a gone exempt entry is reported for a hand edit, not dropped')
    assert.deepEqual(update.unusedRaises, ['server/db/schema.ts'], '--raise has nothing to do on an exempt entry')
    assert.deepEqual(update.baseline[dashboard], { value: 2000, reason: (baseline[dashboard] as { reason: string }).reason }, '--raise keeps a capped entry capped')
    const exemptKeys = (b: Baseline) => Object.keys(b).filter(file => isExempt(b[file]!)).sort()
    assert.deepEqual(exemptKeys(update.baseline), exemptKeys(baseline), '--update added or removed an exempt entry')
  })
})
