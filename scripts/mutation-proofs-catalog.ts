  /** Đoạn mã gốc — phải xuất hiện đúng một lần trong tệp. */
  find: string
  /** Đoạn thay thế (bất biến bị gỡ). */
  replace: string
  /** Các tệp test mà ít nhất một test trong đó phải đỏ. */
  tests: string[]
  /** Bất biến nào, và vì sao nó đáng giữ. */
  why: string
