/**
 * Chụp lược đồ (chỉ DDL, không dữ liệu) của một bản phát hành CŨ, làm fixture cho
 * `tests/schema-upgrade-integration.test.ts`.
 *
 * Suite đó chứng minh trên MySQL thật rằng khởi động bản MỚI trên CSDL của bản CŨ
 * giữ nguyên dữ liệu. "CSDL của bản cũ" phải là lược đồ mà `initDb()` của chính
 * bản cũ dựng ra — không phải lược đồ hiện tại trừ đi vài cột đoán tay. Script này
 * dựng nó đúng như vậy:
 *
 *   1. `git archive <ref>` vào một thư mục tạm (không đụng cây làm việc);
 *   2. chạy `server/db/init.ts` CỦA REF ĐÓ (tiến trình con, dùng `scripts/ts-resolver.mjs`
 *      của ref đó) vào một CSDL dùng-một-lần `cdkt_snapshot_<thời điểm>_<pid>`;
 *   3. đọc `SHOW CREATE TABLE` từng bảng — đúng thứ `mysqldump --no-data` in ra — rồi
 *      xoá CSDL tạm và thư mục tạm (cả khi lỗi).
 *
 * Vì sao không gọi `mysqldump`: máy dev thường không có client MySQL (chỉ có trong
 * container), và `server/services/backup-sql.ts` cũng dump bằng `SHOW CREATE TABLE`
 * trong Node. Kết quả xác định: bảng xếp theo tên, bỏ bộ đếm `AUTO_INCREMENT=` (init
 * chèn sẵn `categories`/`content_types` nên bộ đếm khác 0), không ngày giờ, không
 * DEFINER. Chạy hai lần cho ra cùng từng byte.
 *
 * File không có `DROP TABLE`: lỡ chạy vào một CSDL đã có bảng thì câu `CREATE TABLE`
 * đầu tiên lỗi, không thay thế gì. Nó nằm ở `tests/fixtures/` chứ không ở
 * `migrations/` (thư mục đó có guard chặn chạy nhầm).
 *
 * Dùng (làm mới khi một bản phát hành lên production — xem CI-CD.md):
 *
 *   SNAPSHOT_DB_PORT=33069 SNAPSHOT_DB_PASSWORD=… \
 *     node --experimental-strip-types --import ./scripts/ts-resolver.mjs \
 *     scripts/snapshot-schema.ts --ref <commit đang chạy trên production> [--out tests/fixtures/schema-prev.sql]
 *
 * Biến: `SNAPSHOT_DB_HOST` (127.0.0.1), `SNAPSHOT_DB_PORT` (3306), `SNAPSHOT_DB_USER`
 * (root), `SNAPSHOT_DB_PASSWORD` (rỗng). Cần quyền CREATE/DROP DATABASE. Phụ thuộc
 * (`mysql2`) lấy từ `node_modules` của checkout hiện tại qua symlink — `init.ts` của
 * bản cũ chỉ import `mysql2` và mã của chính nó; nếu một bản cũ cần gói khác, tiến
 * trình con lỗi rõ ràng chứ không âm thầm.
 */
import { spawnSync } from 'node:child_process'
import { mkdtempSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import mysql, { type RowDataPacket } from 'mysql2/promise'

export interface TableDdl {
  name: string
  ddl: string
}

export interface SnapshotMeta {
  ref: string
  commit: string
  server: string
}

const DISPOSABLE_DB = /^cdkt_snapshot_\d+_\d+$/

/** Bộ đếm tự tăng là dữ liệu, không phải lược đồ — và làm hai lần chụp khác nhau. */
export function normalizeCreateTable(ddl: string): string {
  return ddl.replace(/ AUTO_INCREMENT=\d+/g, '').trimEnd()
}

export function renderSchemaSnapshot(meta: SnapshotMeta, tables: TableDdl[]): string {
  const sorted = [...tables].sort((a, b) => a.name.localeCompare(b.name))
  const lines = [
    '-- Schema snapshot of a previous release for tests/schema-upgrade-integration.test.ts.',
    '-- Generated by scripts/snapshot-schema.ts. Do not edit by hand; refresh it as CI-CD.md describes.',
    `-- ref: ${meta.ref}`,
    `-- commit: ${meta.commit}`,
    `-- server: ${meta.server}`,
    `-- tables: ${sorted.length}`,
    '-- Schema only: no rows and no DROP statements. Loaded into a database that already',
    '-- has these tables, the first CREATE TABLE fails instead of replacing anything.',
    'SET NAMES utf8mb4;',
    'SET FOREIGN_KEY_CHECKS=0;',
    '',
  ]
  for (const table of sorted) lines.push(`${normalizeCreateTable(table.ddl)};`, '')
  lines.push('SET FOREIGN_KEY_CHECKS=1;', '')
  return lines.join('\n')
}

type Connect = { host: string, port: number, user: string, password: string }

function git(repoRoot: string, args: string[], encoding: 'utf8' | 'buffer' = 'utf8') {
  const result = spawnSync('git', args, { cwd: repoRoot, encoding: encoding === 'utf8' ? 'utf8' : undefined, maxBuffer: 512 * 1024 * 1024 })
  if (result.status !== 0) throw new Error(`git ${args.join(' ')} failed (exit ${result.status}): ${String(result.stderr)}`)
  return result.stdout
}

/** Đọc lược đồ của CSDL tạm. Ngoài bảng thường ra (view, trigger, routine, event) thì dừng: fixture sẽ thiếu. */
async function readSchema(connect: Connect, database: string): Promise<{ server: string, tables: TableDdl[] }> {
  const conn = await mysql.createConnection({ ...connect, database })
  try {
    // `SHOW CREATE TABLE` đổi cách trích dẫn theo `ANSI_QUOTES`; ghim để file chỉ có một cách đọc.
    await conn.query("SET SESSION sql_mode = 'NO_ENGINE_SUBSTITUTION'")
    const [[version]] = await conn.query<RowDataPacket[]>('SELECT VERSION() AS v')
    const [objects] = await conn.query<RowDataPacket[]>(
      `SELECT 'view' AS kind, TABLE_NAME AS name FROM information_schema.VIEWS WHERE TABLE_SCHEMA = ?
       UNION ALL SELECT 'trigger', TRIGGER_NAME FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = ?
       UNION ALL SELECT 'routine', ROUTINE_NAME FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA = ?
       UNION ALL SELECT 'event', EVENT_NAME FROM information_schema.EVENTS WHERE EVENT_SCHEMA = ?`,
      [database, database, database, database],
    )
    if (objects.length > 0) {
      throw new Error(`the release created objects this script does not snapshot: ${objects.map(o => `${o.kind} ${o.name}`).join(', ')}`)
    }
    const [rows] = await conn.query<RowDataPacket[]>(
      "SELECT TABLE_NAME AS name FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME",
      [database],
    )
    const tables: TableDdl[] = []
    for (const row of rows) {
      const name = String(row.name)
      const [create] = await conn.query<RowDataPacket[]>(`SHOW CREATE TABLE \`${name}\``)
      tables.push({ name, ddl: String(create[0]?.['Create Table'] ?? '') })
    }
    return { server: `MySQL ${String(version?.v)}`, tables }
  } finally {
    await conn.end()
  }
}

export async function snapshotRelease(options: { repoRoot: string, ref: string, connect: Connect }): Promise<string> {
  const { repoRoot, ref, connect } = options
  const commit = String(git(repoRoot, ['rev-parse', '--verify', `${ref}^{commit}`])).trim()
  const database = `cdkt_snapshot_${Date.now()}_${process.pid}`
  if (!DISPOSABLE_DB.test(database)) throw new Error(`refusing to use database ${database}`)

  const workDir = mkdtempSync(path.join(os.tmpdir(), 'cdkt-snapshot-'))
  // Dọn dẹp ở MỌI đường ra: thư mục tạm (bản sao repo ~30 MB) xoá trước, rồi CSDL
  // tạm. Lỗi được báo là lỗi ĐẦU TIÊN. Máy chủ không tới được hay sai mật khẩu thì
  // DROP cũng hỏng, nhưng không được che lỗi gốc và không được giữ thư mục tạm lại.
  let failure: unknown = null
  let snapshot = ''
  try {
    snapshot = await buildSnapshot({ repoRoot, ref, connect, commit, database, workDir })
  } catch (err) {
    failure = err
  }
  rmSync(workDir, { recursive: true, force: true })
  try {
    await dropDatabase(connect, database)
  } catch (err) {
    failure ??= err
  }
  if (failure) throw failure
  return snapshot
}

async function dropDatabase(connect: Connect, database: string) {
  if (!DISPOSABLE_DB.test(database)) throw new Error(`refusing to drop database ${database}`)
  const conn = await mysql.createConnection(connect)
  try {
    await conn.query(`DROP DATABASE IF EXISTS \`${database}\``)
  } finally {
    await conn.end()
  }
}

/** The previous release's init on a throwaway database, then its schema. */
async function buildSnapshot(options: { repoRoot: string, ref: string, connect: Connect, commit: string, database: string, workDir: string }): Promise<string> {
  const { repoRoot, ref, connect, commit, database, workDir } = options
  const archive = git(repoRoot, ['archive', '--format=tar', commit], 'buffer')
  const untar = spawnSync('tar', ['-x', '-C', workDir], { input: archive })
  if (untar.status !== 0) throw new Error(`tar -x failed (exit ${untar.status}): ${String(untar.stderr)}`)
  symlinkSync(path.join(repoRoot, 'node_modules'), path.join(workDir, 'node_modules'), 'dir')

  // Đúng lệnh `db:init` của bản đó, với CSDL tạm và các biến kết nối của script này.
  const init = spawnSync(
    process.execPath,
    ['--experimental-strip-types', '--import', './scripts/ts-resolver.mjs', 'server/db/init.ts'],
    {
      cwd: workDir,
      encoding: 'utf8',
      timeout: 300_000,
      killSignal: 'SIGKILL',
      env: {
        ...process.env,
        DB_HOST: connect.host,
        DB_PORT: String(connect.port),
        DB_USER: connect.user,
        DB_PASSWORD: connect.password,
        DB_NAME: database,
      },
    },
  )
  if (init.status !== 0) throw new Error(`init.ts of ${commit} failed (exit ${init.status}${init.signal ? `, ${init.signal}` : ''})\n${init.stdout}\n${init.stderr}`)

  const { server, tables } = await readSchema(connect, database)
  if (tables.length === 0) throw new Error(`init.ts of ${commit} created no tables in ${database}`)
  return renderSchemaSnapshot({ ref, commit, server }, tables)
}

function argValue(name: string): string | undefined {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

async function main() {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
  const ref = argValue('--ref')
  if (!ref) {
    console.error('usage: snapshot-schema.ts --ref <git ref of the release on production> [--out tests/fixtures/schema-prev.sql]')
    process.exit(2)
  }
  const out = path.resolve(repoRoot, argValue('--out') ?? 'tests/fixtures/schema-prev.sql')
  const sql = await snapshotRelease({
    repoRoot,
    ref,
    connect: {
      host: process.env.SNAPSHOT_DB_HOST || '127.0.0.1',
      port: Number(process.env.SNAPSHOT_DB_PORT || 3306),
      user: process.env.SNAPSHOT_DB_USER || 'root',
      password: process.env.SNAPSHOT_DB_PASSWORD || '',
    },
  })
  writeFileSync(out, sql)
  console.log(`wrote ${path.relative(repoRoot, out)} (${sql.length} bytes) from ${ref}`)
}

// Chạy khi gọi trực tiếp; import (để dùng các hàm thuần) thì không. Chuẩn hoá dấu
// gạch như `server/db/init.ts`, để checkout Windows không thoát 0 mà không làm gì.
if ((process.argv[1] || '').replaceAll('\\', '/').endsWith('scripts/snapshot-schema.ts')) {
  main().catch((err: unknown) => {
    console.error('❌ snapshot-schema failed:', err instanceof Error ? err.message : err)
    process.exit(1)
  })
}
